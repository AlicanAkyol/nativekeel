#!/usr/bin/env node
// Prints, for each CocoaPods pod on Apple's list of SDKs that need a privacy manifest
// (developer.apple.com/support/third-party-SDK-requirements), the first released version whose
// podspec ships a PrivacyInfo.xcprivacy. Read from the CocoaPods Specs repository, so the table in
// src/privacy-sdks.js is generated, not typed by hand:
//   node scripts/privacy-sdk-table.mjs > /tmp/rows.txt   (needs `gh` logged in for the API)
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';

// Pod names for the SDKs on Apple's list that appear in React Native apps (Flutter/Cordova-only
// entries are left out). "Apple name": [pod names].
const SDKS = {
  Abseil: ['abseil'], AFNetworking: ['AFNetworking'], Alamofire: ['Alamofire'], AppAuth: ['AppAuth'],
  'BoringSSL / openssl_grpc': ['BoringSSL-GRPC'], Charts: ['Charts', 'DGCharts'], FMDB: ['FMDB'],
  FBAEMKit: ['FBAEMKit'], FBSDKCoreKit: ['FBSDKCoreKit'], FBSDKCoreKit_Basics: ['FBSDKCoreKit_Basics'], FBSDKLoginKit: ['FBSDKLoginKit'], FBSDKShareKit: ['FBSDKShareKit'],
  FBLPromises: ['PromisesObjC'], Promises: ['PromisesSwift'],
  FirebaseABTesting: ['FirebaseABTesting'], FirebaseAuth: ['FirebaseAuth'], FirebaseCore: ['FirebaseCore'], FirebaseCoreDiagnostics: ['FirebaseCoreDiagnostics'], FirebaseCoreExtension: ['FirebaseCoreExtension'], FirebaseCoreInternal: ['FirebaseCoreInternal'], FirebaseCrashlytics: ['FirebaseCrashlytics'], FirebaseDynamicLinks: ['FirebaseDynamicLinks'], FirebaseFirestore: ['FirebaseFirestore'], FirebaseInstallations: ['FirebaseInstallations'], FirebaseMessaging: ['FirebaseMessaging'], FirebaseRemoteConfig: ['FirebaseRemoteConfig'],
  GoogleDataTransport: ['GoogleDataTransport'], GoogleSignIn: ['GoogleSignIn'], GoogleToolboxForMac: ['GoogleToolboxForMac'], GoogleUtilities: ['GoogleUtilities'], grpcpp: ['gRPC-C++'], GTMAppAuth: ['GTMAppAuth'], GTMSessionFetcher: ['GTMSessionFetcher'],
  IQKeyboardManager: ['IQKeyboardManager'], IQKeyboardManagerSwift: ['IQKeyboardManagerSwift'], Kingfisher: ['Kingfisher'], leveldb: ['leveldb-library'], Lottie: ['lottie-ios'], MBProgressHUD: ['MBProgressHUD'], nanopb: ['nanopb'],
  OneSignal: ['OneSignalXCFramework'], OpenSSL: ['OpenSSL-Universal'], OrderedSet: ['OrderedSet'], Protobuf: ['Protobuf'], Reachability: ['Reachability', 'ReachabilitySwift'], RealmSwift: ['RealmSwift'],
  RxCocoa: ['RxCocoa'], RxRelay: ['RxRelay'], RxSwift: ['RxSwift'], SDWebImage: ['SDWebImage'], SnapKit: ['SnapKit'], Starscream: ['Starscream'], SVProgressHUD: ['SVProgressHUD'], SwiftyGif: ['SwiftyGif'], SwiftyJSON: ['SwiftyJSON'], Toast: ['Toast'],
};

const shard = (pod) => crypto.createHash('md5').update(pod).digest('hex').slice(0, 3).split('').join('/');
const gh = (p) => JSON.parse(execFileSync('gh', ['api', p], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }));
const cmp = (a, b) => {
  const pa = a.split(/[.-]/).map((x) => (/^\d+$/.test(x) ? Number(x) : -1));
  const pb = b.split(/[.-]/).map((x) => (/^\d+$/.test(x) ? Number(x) : -1));
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) if ((pa[i] ?? 0) !== (pb[i] ?? 0)) return (pa[i] ?? 0) - (pb[i] ?? 0);
  return 0;
};
const specHas = async (pod, v) => {
  const url = `https://raw.githubusercontent.com/CocoaPods/Specs/master/Specs/${shard(pod)}/${pod}/${v}/${pod}.podspec.json`;
  const res = await fetch(url);
  if (!res.ok) return null;
  return /PrivacyInfo|xcprivacy/i.test(await res.text());
};

const rows = [];
for (const [apple, pods] of Object.entries(SDKS)) {
  for (const pod of pods) {
    let versions;
    try {
      versions = gh(`repos/CocoaPods/Specs/contents/Specs/${shard(pod)}/${pod}`).map((e) => e.name).filter((v) => /^\d+(\.\d+)*$/.test(v)).sort(cmp);
    } catch {
      console.error(`skip ${pod}: not on trunk`);
      continue;
    }
    if (!versions.length) continue;
    const latest = versions.at(-1);
    if (!(await specHas(pod, latest))) {
      rows.push({ apple, pod, first: null, latest });
      continue;
    }
    // Binary search for the first version with a manifest (they are not removed once added).
    let lo = 0;
    let hi = versions.length - 1;
    while (lo < hi) {
      const mid = (lo + hi) >> 1;
      if (await specHas(pod, versions[mid])) hi = mid;
      else lo = mid + 1;
    }
    rows.push({ apple, pod, first: versions[lo], latest });
  }
}
console.log(`  // Generated by scripts/privacy-sdk-table.mjs on ${new Date().toISOString().slice(0, 10)} from the CocoaPods Specs repo.`);
for (const r of rows) console.log(`  '${r.pod}': { sdk: '${r.apple}', firstWithManifest: ${r.first ? `'${r.first}'` : 'null'}, latest: '${r.latest}' },`);
